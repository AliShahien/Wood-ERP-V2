// Generates the REST endpoint catalog from the route files:
//  - apps/web/src/server/openapi.json  (served at /api/v1/openapi.json)
//  - docs/API-ENDPOINTS.md
// Usage: node scripts/gen-api-docs.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const apiDir = path.join(root, "apps/web/src/app/api");
const routes = [];
function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === "route.ts") {
      const src = readFileSync(p, "utf8");
      const methods = [...src.matchAll(/export (?:const|async function) (GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]);
      const perms = [...new Set([...src.matchAll(/(\w+)\.(\w+)\(/g)].map((m) => `${m[1]}.${m[2]}`).filter((s) => !/^(req|ctx|res|NextResponse|log|jobs\.run|Buffer)/.test(s)))];
      const rel = path.relative(apiDir, path.dirname(p)).replace(/\\/g, "/").replace(/\[\.\.\.(\w+)\]/g, "{$1*}").replace(/\[(\w+)\]/g, "{$1}");
      routes.push({ path: `/api/${rel}`, methods, handler: perms.slice(0, 3).join(", ") });
    }
  }
}
walk(apiDir);
routes.sort((a, b) => a.path.localeCompare(b.path));

const openapi = {
  openapi: "3.1.0",
  info: { title: "Edge Wood ERP API", version: "1.0.0", description: "Cookie-session authenticated REST API. Mutations require an Origin header equal to APP_URL. Errors: { error: { code, messageKey, details } }." },
  components: { securitySchemes: { session: { type: "apiKey", in: "cookie", name: "edge_session" } } },
  security: [{ session: [] }],
  paths: Object.fromEntries(routes.map((r) => [r.path, Object.fromEntries(r.methods.map((m) => [m.toLowerCase(), {
    summary: r.handler || r.path,
    parameters: [...r.path.matchAll(/\{(\w+)\*?\}/g)].map((x) => ({ name: x[1], in: "path", required: true, schema: { type: "string" } })),
    responses: { 200: { description: "OK" }, 401: { description: "UNAUTHENTICATED" }, 403: { description: "FORBIDDEN" }, 404: { description: "NOT_FOUND" }, 409: { description: "CONFLICT / INVALID_TRANSITION / INSUFFICIENT_STOCK / IMMUTABLE" }, 422: { description: "VALIDATION" } },
  }]))])),
};
writeFileSync(path.join(root, "apps/web/src/server/openapi.json"), JSON.stringify(openapi, null, 1));

const md = [
  "# API endpoint catalog",
  "",
  `Generated by \`node scripts/gen-api-docs.mjs\` — ${routes.length} routes. Machine-readable: \`GET /api/v1/openapi.json\`.`,
  "Conventions, auth and errors: see [API.md](API.md). Each handler enforces its own permission in `@edge/core`.",
  "",
  "| Path | Methods | Service |",
  "|---|---|---|",
  ...routes.map((r) => `| \`${r.path}\` | ${r.methods.join(", ")} | ${r.handler.replace(/\|/g, "\\|")} |`),
  "",
].join("\n");
writeFileSync(path.join(root, "docs/API-ENDPOINTS.md"), md);
console.log(`${routes.length} routes documented`);
